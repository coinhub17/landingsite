
import streamlit as st
import hashlib
import uuid
import datetime
import io
import os
import tempfile
from fpdf import FPDF
from PIL import Image, UnidentifiedImageError

# ---------- CONFIG ----------
ADMIN_PASSWORD = os.getenv("Rorokin9ne", "KVN_ADMIN_SECRET")

# ---------- PAGE CONFIG ----------
st.set_page_config(
    page_title="Kerio Valley Network IP Protection",
    page_icon="📜",
    layout="centered"
)

# ---------- MEMORY ----------
if "cert_store" not in st.session_state:
    st.session_state.cert_store = {}

if "last_cert_id" not in st.session_state:
    st.session_state.last_cert_id = None

if "admin_mode" not in st.session_state:
    st.session_state.admin_mode = False

# ---------- HASH ----------
def hash_file(file_bytes):
    return hashlib.sha256(file_bytes).hexdigest()


# ---------- PDF GENERATION ----------
def generate_pdf(cert, image_bytes=None):

    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()

    # Light watermark
    pdf.set_font("Helvetica", "B", 42)
    pdf.set_text_color(238, 238, 238)
    pdf.set_xy(10, 125)
    pdf.cell(190, 25, "KV Network IP Protection", align="C")

    # Header
    pdf.set_y(20)
    pdf.set_font("Helvetica", "B", 18)
    pdf.set_text_color(0, 51, 102)
    pdf.cell(
        0, 15,
        "Kerio Valley Network IP Protection Certificate",
        ln=True,
        align="C"
    )

    pdf.set_draw_color(0, 51, 102)
    pdf.line(10, 40, 200, 40)
    pdf.ln(12)

    # Certificate information
    def add_field(label, value, size=10):
        pdf.set_font("Helvetica", "B", size)
        pdf.set_text_color(30, 30, 30)
        pdf.cell(0, 8, label, ln=True)

        pdf.set_font("Helvetica", "", size)
        pdf.set_text_color(70, 70, 70)
        pdf.multi_cell(0, 7, str(value))
        pdf.ln(2)

    add_field("Certificate ID:", cert["id"])
    add_field("Author / Creator:", cert["author"])
    add_field("Title of Work:", cert["title"])
    add_field("Filename:", cert["filename"])
    add_field("SHA-256 Fingerprint:", cert["file_hash"], 8)
    add_field("Timestamp (UTC):", cert["timestamp"])

    # Declaration
    pdf.ln(4)
    pdf.set_font("Helvetica", "B", 12)
    pdf.set_text_color(0, 51, 102)
    pdf.cell(0, 9, "Author Declaration", ln=True)

    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(50, 50, 50)
    pdf.multi_cell(0, 7, cert["declaration"])

    # Image preview, if available
    if image_bytes:
        try:
            img = Image.open(io.BytesIO(image_bytes))
            img.verify()

            img = Image.open(io.BytesIO(image_bytes))
            img = img.convert("RGB")

            with tempfile.NamedTemporaryFile(
                suffix=".jpg", delete=False
            ) as temp:
                temp_path = temp.name
                img.save(temp_path, format="JPEG")

            pdf.add_page()
            pdf.set_font("Helvetica", "B", 14)
            pdf.set_text_color(0, 51, 102)
            pdf.cell(0, 12, "Certified Work Preview", ln=True, align="C")
            pdf.image(temp_path, x=20, y=35, w=170)

            os.unlink(temp_path)

        except (UnidentifiedImageError, OSError, ValueError):
            pass

    # Certification note
    pdf.ln(8)
    pdf.set_font("Helvetica", "I", 9)
    pdf.set_text_color(100, 100, 100)

    pdf.multi_cell(
        0, 6,
        "This certificate is digitally signed. "
        "The author's declaration represents information supplied "
        "by the client. This certificate does not independently "
        "establish authorship or legal ownership."
    )

    # Footer
    pdf.ln(5)
    pdf.set_font("Helvetica", "B", 11)
    pdf.set_text_color(0, 102, 153)
    pdf.cell(0, 9, "Generated by KV Network IP Protection System",
             ln=True, align="R")

    # Compatible PDF output
    output = pdf.output(dest="S")

    if isinstance(output, str):
        output = output.encode("latin1")
    else:
        output = bytes(output)

    return output


# ---------- MAIN UI ----------
st.title("📜 Kerio Valley Network IP Protection System")
st.caption("Digital signing and Fingerprinting records")

# ---------- CLIENT DETAILS ----------
st.header("1. Creator Information")

author = st.text_input("Author / Creator Name")
id_number = st.text_input(
    "National ID Number",
    max_chars=20,
    placeholder="Enter your ID number")
work_title = st.text_input("Title of Work")

declaration = st.text_area(
    "Ownership / Copyright Declaration",
    value=(
        "I declare that I am submitting this work for digital "
        "signing and fingerprint verification. "
        "The information provided is accurate to the best of my knowledge."
    ),
    height=130
)

# ---------- WORK SUBMISSION ----------
st.header("2. Submit Your Work")

submission_type = st.radio(
    "Choose submission method",
    ["Upload Existing File", "Write New Text Document"]
)

content = None
filename = None
image_bytes = None

if submission_type == "Upload Existing File":

    uploaded_file = st.file_uploader(
        "Upload your work",
        key="original_upload"
    )

    if uploaded_file is not None:
        content = uploaded_file.getvalue()
        filename = uploaded_file.name

        # Check if uploaded file is an image
        try:
            Image.open(io.BytesIO(content)).verify()
            image_bytes = content
        except (UnidentifiedImageError, OSError, ValueError):
            image_bytes = None

        st.success("File ready for certification.")
        st.write("Filename:", filename)
        st.write("File size:", f"{len(content):,} bytes")

else:

    document_text = st.text_area(
        "Write your original work here",
        height=300,
        placeholder="Start writing your work..."
    )

    if document_text.strip():
        content = document_text.encode("utf-8")
        filename = "IPLOCAL_Text_Work.txt"

        st.info(
            "Your written text will be saved as a UTF-8 text document "
            "and its actual contents will be hashed."
        )


# ---------- CREATE CERTIFICATE ----------
st.header("3. Generate Certificate")

if st.button("Generate IP Certificate", type="primary"):

    if not author.strip():
        st.error("Please enter the author / creator name.")

    elif not id_number.strip():
        st.error("Please enter your National ID Number.")

    elif not work_title.strip():
        st.error("Please enter the title of your work.")

    elif not declaration.strip():
        st.error("Please enter your declaration.")

    elif content is None or not content:
        st.error("Please upload a file or write your work first.")

    else:

        file_hash = hash_file(content)

        cert_id = "KV Network-" + uuid.uuid4().hex[:12].upper()

        timestamp = datetime.datetime.now(
            datetime.timezone.utc
        ).strftime("%Y-%m-%d %H:%M:%S UTC")

        cert = {
            "id": cert_id,
            "author": author.strip(),
            "id_number": id_number.strip(),
            "title": work_title.strip(),
            "declaration": declaration.strip(),
            "file_hash": file_hash,
            "timestamp": timestamp,
            "filename": filename,
            "file_bytes": content,
            "submission_type": submission_type
        }

        st.session_state.cert_store[cert_id] = cert
        st.session_state.last_cert_id = cert_id

        st.success("Certificate record created successfully!")

        st.write("Certificate ID:", cert_id)
        st.write("SHA-256:", file_hash)
        st.write("Timestamp:", timestamp)


# ---------- CLIENT CERTIFICATE DOWNLOAD ----------
if st.session_state.last_cert_id:

    cert = st.session_state.cert_store.get(
        st.session_state.last_cert_id
    )

    if cert:

        st.divider()
        st.subheader("Your Certificate")

        pdf = generate_pdf(cert, image_bytes=image_bytes)

        st.download_button(
            "Download IP Certificate",
            data=pdf,
            file_name=f"KV Network_{cert['id']}.pdf",
            mime="application/pdf",
            key=f"client_download_{cert['id']}"
        )


# ---------- VERIFY ----------
st.divider()
st.header("4. Verify Submitted Work")

verify_file = st.file_uploader(
    "Re-upload the original certified file",
    key="verify_upload"
)

verify_national_id = st.text_input(
    "Enter National ID Number for verification",
    max_chars=20
)

if st.button("Verify File"):

    if verify_file is None:
        st.error("Please upload the file you want to verify.")
    elif not verify_national_id.strip():
        st.error("Please enter your National ID Number.")

    else:
        verify_bytes = verify_file.getvalue()
        verify_hash = hash_file(verify_bytes)

        if verify_national_id.strip():

            matches = [
                cert for cert in st.session_state.cert_store.values()
                if cert.get("id_number", "").strip().lower()
                == verify_national_id.strip().lower()
            ]

            if any(cert["file_hash"] == verify_hash for cert in matches):

                st.success("✅ FILE VERIFIED SUCCESSFULLY")

                for cert in matches:
                    if cert["file_hash"] == verify_hash:
                        st.write("Certificate ID:", cert["id"])
                        st.write("Author:", cert["author"])
                        st.write("Work:", cert["title"])
                        st.write("Timestamp:", cert["timestamp"])

            else:
                st.error("❌ FILE MISMATCH: ID found, but file does not match.")


# ---------- ADMIN ----------
st.divider()
st.subheader("5. Administrator Access")

password = st.text_input(
    "Administrator Password",
    type="password"
)

if st.button("Admin Login"):

    if password == ADMIN_PASSWORD:
        st.session_state.admin_mode = True
        st.success("Administrator access enabled.")
    else:
        st.session_state.admin_mode = False
        st.error("Incorrect administrator password.")


# ---------- ADMIN CERTIFICATE MANAGEMENT ----------
if st.session_state.admin_mode:

    st.subheader("Administrator Certificate Records")

    if st.session_state.cert_store:

        st.write(
            "Total certificates:",
            len(st.session_state.cert_store)
        )

        for cert_id, cert in st.session_state.cert_store.items():

            with st.expander(
                f"{cert['title']} — {cert_id}"
            ):

                st.write("Author:", cert["author"])
                st.write("Filename:", cert["filename"])
                st.write("Timestamp:", cert["timestamp"])
                st.code(cert["file_hash"])

                image_preview = None

                try:
                    Image.open(
                        io.BytesIO(cert["file_bytes"])
                    ).verify()
                    image_preview = cert["file_bytes"]
                except (UnidentifiedImageError, OSError, ValueError):
                    pass

                admin_pdf = generate_pdf(cert, image_preview)

                st.download_button(
                    "Download Admin Certificate",
                    data=admin_pdf,
                    file_name=f"KVN_{cert_id}.pdf",
                    mime="application/pdf",
                    key=f"admin_download_{cert_id}"
                )

    else:
        st.info("No certificate records available yet.")

    if st.button("Logout Admin"):
        st.session_state.admin_mode = False
        st.rerun()
